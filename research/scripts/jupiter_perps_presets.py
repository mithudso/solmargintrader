"""Export positive baseline rows the Perps paper signal engine can express."""

import json
from pathlib import Path

from research.zec_live import STEPS, load_winners

OUTPUT = Path(__file__).resolve().parents[2] / "extension/src/perps/archive-presets.js"
SUPPORTED = {"rsi", "zscore", "bb_reversion"}


def main():
    presets = []
    for winner in load_winners():
        config = winner["config"]
        if (
            winner["mode"] != "baseline"
            or not config
            or config["mode"] not in {"single", "mean"}
            or config.get("gate")
            or config.get("fallback")
            or config.get("persistence", 1) != 1
            or config.get("rebalance_threshold", 0)
            or any(member["strategy"] not in SUPPORTED for member in config["members"])
        ):
            continue
        identifier = winner["candidate_id"]
        interval = winner["interval"]
        names = " + ".join(member["strategy"].replace("_", " ") for member in config["members"])
        fees = ", ".join(str(fee) for fee in sorted(winner["winning_fee_bps"]))
        presets.append({
            "id": f"archive-{identifier}-{interval}",
            "name": f"ZEC {interval} · {names} · {identifier[:6]}",
            "assets": ["ZEC"],
            "step": STEPS[interval],
            "kind": "archive",
            "members": config["members"],
            "source": f"Frozen ZEC expanded Coinbase study {identifier}; positive spot reference at {fees} bps.",
            "details": " · ".join(
                f'{member["strategy"]} {json.dumps(member["params"], sort_keys=True)}'
                for member in config["members"]
            ),
        })
    OUTPUT.write_text(
        "// Generated by python -m research.jupiter_perps_presets.\n"
        "export const ARCHIVE_PRESETS = " + json.dumps(presets, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
