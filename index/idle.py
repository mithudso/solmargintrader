"""Idle index check: rebuild the semantic index in the background when it is out of date.

    python3 index/idle.py --status      # fresh / stale / missing, and why
    python3 index/idle.py --once        # check; start a background rebuild if warranted
    python3 index/idle.py --force       # rebuild now, ignoring load and throttle (foreground)
    python3 index/idle.py --install-schedule    # hourly launchd agent (macOS): runs --once
    python3 index/idle.py --uninstall-schedule

`search.py` and the soltui Docs tab call `maybe_start()` themselves, so the index keeps
itself current without a daemon. For a schedule, run `--once` from cron or launchd.

A background rebuild starts only when ALL of these hold:

1. the semantic index is missing or out of date for the files it covers;
2. the machine is idle (1-minute load average below `INDEX_IDLE_THRESHOLD`, default 2.0,
   the same rule as the hub's idle indexer) **or an hour has passed** since the last rebuild
   started (`FORCE_INTERVAL`, override with `INDEX_FORCE_INTERVAL` seconds, 0 turns the hourly
   sweep off). A busy Mac never goes idle, so without the hourly sweep it would never reindex;
   the rebuild is `nice 19` and lock-guarded, so running it under load is safe;
3. no other rebuild holds `index/.idle.lock`;
4. a local ollama answers (it is started if needed) and `mxbai-embed-large:latest` is
   installed. The model is **never downloaded** by this job: ~670 MB is a decision.
5. the last check was more than `MIN_INTERVAL` seconds ago, so a burst of searches does not
   re-hash the tree each time.

**It writes only gitignored files** (`semantic-local.npz`, `semantic-local.json`, the lock,
the state and a log), so a background run never makes `git status` dirty. The committed
keyword index is deliberately not touched here: it is regenerated by `build.py all`, gated
by `build.py --check` in CI, and rewriting a 12 MB tracked file on a timer would make every
checkout permanently dirty.

Set `INDEX_NO_AUTO=1` to disable the automatic start entirely.
"""

from __future__ import annotations

import argparse
import fcntl
import json
import os
import plistlib
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import build  # noqa: E402
import ollama_ensure  # noqa: E402

OUT = build.OUT
STATE_FILE = OUT / ".idle-state.json"
LOCK_FILE = OUT / ".idle.lock"
LOG_FILE = OUT / ".idle-index.log"
MIN_INTERVAL = 600.0
DEFAULT_THRESHOLD = 2.0
FORCE_INTERVAL = 3600.0

LABEL = "com.mitchhudson.solmargintrader.index"
DEFAULT_PYTHON = Path.home() / ".venvs" / "soltui" / "bin" / "python"


def active_manifest() -> tuple[Path, Path] | None:
    """(manifest, array) of the semantic pair search would use, or None when neither exists."""
    for manifest, npz in ((build.LOCAL_MANIFEST, build.LOCAL_NPZ),
                          (build.SEMANTIC_MANIFEST, build.SEMANTIC_NPZ)):
        if manifest.exists() and npz.exists():
            return manifest, npz
    return None


def semantic_status() -> tuple[str, str]:
    """('fresh'|'stale'|'missing', why). Hashes the tree; a few hundred small files."""
    pair = active_manifest()
    if pair is None:
        return "missing", "no semantic index is built"
    try:
        manifest = json.loads(pair[0].read_text())
    except (OSError, ValueError):
        return "stale", f"{pair[0].name} is unreadable"
    if manifest.get("model") and not ollama_ensure.model_matches(
            [manifest["model"]], ollama_ensure.EMBED_MODEL):
        return "stale", f"built with {manifest['model']}, current model is {ollama_ensure.EMBED_MODEL}"
    recorded: dict[str, str] = manifest.get("sourceSha1") or {}
    changed: list[str] = []
    for rel in build.tracked_files():
        path = build.REPO / rel
        ext = path.suffix
        if ext in build.BODY_EXCLUDED_EXT or ext not in build.TEXT_EXT or not path.is_file():
            continue
        if rel in recorded:
            if build.sha1_of(path) != recorded[rel]:
                changed.append(rel)
        elif build.chunks_of(build.read_text(path)):
            changed.append(rel)   # a file the index would embed but has never seen
    gone = [p for p in recorded if not (build.REPO / p).is_file()]
    if changed or gone:
        return "stale", f"{len(changed)} changed or new, {len(gone)} removed since it was built"
    return "fresh", f"{len(recorded)} files, built {manifest.get('generatedAt', '?')}"


def is_idle(threshold: float | None = None) -> bool:
    limit = threshold if threshold is not None else float(
        os.environ.get("INDEX_IDLE_THRESHOLD", DEFAULT_THRESHOLD))
    try:
        return os.getloadavg()[0] < limit
    except OSError:  # no load average on this platform: do not block on it
        return True


def force_interval() -> float:
    """Seconds after which a rebuild is due even on a busy machine; 0 means never."""
    try:
        return max(0.0, float(os.environ.get("INDEX_FORCE_INTERVAL", FORCE_INTERVAL)))
    except ValueError:
        return FORCE_INTERVAL


def sweep_due(state: dict, now: float) -> bool:
    """True when the hourly sweep applies: enabled, and an hour since a rebuild last started."""
    interval = force_interval()
    return interval > 0 and now - float(state.get("last_build_at", 0)) >= interval


def _read_state() -> dict:
    try:
        return json.loads(STATE_FILE.read_text())
    except (OSError, ValueError):
        return {}


def _write_state(state: dict) -> None:
    try:
        STATE_FILE.write_text(json.dumps(state))
    except OSError:
        pass


def lock_free() -> bool:
    """True when no rebuild holds the lock. Probe only: the lock is released immediately."""
    OUT.mkdir(exist_ok=True)
    fd = os.open(LOCK_FILE, os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        fcntl.flock(fd, fcntl.LOCK_UN)
        return True
    except OSError:
        return False
    finally:
        os.close(fd)


def maybe_start(*, force: bool = False, now: float | None = None, start_ollama: bool = True) -> str:
    """Start a background rebuild if one is warranted; return a one-line reason either way."""
    if os.environ.get("INDEX_NO_AUTO") == "1" and not force:
        return "auto-indexing disabled (INDEX_NO_AUTO=1)"
    clock = time.time() if now is None else now
    state = _read_state()
    if not force and clock - float(state.get("checked_at", 0)) < MIN_INTERVAL:
        return state.get("last", "checked recently")
    status, why = semantic_status()
    if status == "fresh":
        _write_state({**state, "checked_at": clock, "last": f"semantic index is fresh ({why})"})
        return f"semantic index is fresh ({why})"
    busy_sweep = False
    if not force and not is_idle():
        if not sweep_due(state, clock):
            message = f"semantic index is {status} ({why}); machine is busy, next sweep is not due yet"
            _write_state({**state, "checked_at": clock, "last": message})
            return message
        busy_sweep = True
    if not lock_free():
        message = f"semantic index is {status}; a rebuild is already running"
        _write_state({**state, "checked_at": clock, "last": message})
        return message
    ready = ollama_ensure.ensure(ollama_ensure.EMBED_MODEL, **({} if start_ollama else {"start": False}))
    if not ready.ok:
        _write_state({**state, "checked_at": clock,
                      "last": f"semantic index is {status}; {ready.message}"})
        return f"semantic index is {status}; not rebuilding: {ready.message}"
    OUT.mkdir(exist_ok=True)
    try:
        with LOG_FILE.open("ab") as log:
            subprocess.Popen(  # noqa: S603 - argv list, no shell
                ["nice", "-n", "19", sys.executable, str(HERE / "idle.py"), "--run-build"],
                stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, start_new_session=True,
            )
    except OSError as exc:
        message = f"semantic index is {status}; rebuild could not start ({type(exc).__name__})"
        _write_state({**state, "checked_at": clock, "last": message})
        return message
    _write_state({**state, "checked_at": clock, "last_build_at": clock,
                  "last": "rebuild started in the background"})
    reason = "hourly sweep, machine busy" if busy_sweep else "machine idle"
    return (f"semantic index is {status} ({why}); rebuilding in the background "
            f"({reason}; log: {LOG_FILE.name})")


def run_build() -> int:
    """The background job body: take the lock, rebuild, release."""
    OUT.mkdir(exist_ok=True)
    fd = os.open(LOCK_FILE, os.O_CREAT | os.O_RDWR, 0o600)
    try:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            print("another rebuild holds the lock; exiting")
            return 0
        started = time.time()
        code = build.build_semantic(build.build_meta(), local=True)
        print(f"rebuild finished in {time.time() - started:.0f}s with code {code}", flush=True)
        _write_state({**_read_state(), "checked_at": time.time(),
                      "last": "rebuild finished" if code == 0 else "rebuild failed"})
        return code
    finally:
        os.close(fd)


# -- the hourly schedule ---------------------------------------------------------------------------
# A search triggers the check, but a quiet console triggers nothing; a launchd agent runs `--once`
# every hour so the sweep happens on its own.


def agents_dir() -> Path:
    return Path(os.environ.get("INDEX_LAUNCHAGENTS_DIR") or Path.home() / "Library" / "LaunchAgents")


def plist_path() -> Path:
    return agents_dir() / f"{LABEL}.plist"


def plist_dict(python: Path = DEFAULT_PYTHON, repo: Path = build.REPO) -> dict:
    log = Path.home() / "Library" / "Logs" / "solmargintrader" / "index.log"
    return {
        "Label": LABEL,
        "ProgramArguments": [str(python), str(repo / "index" / "idle.py"), "--once"],
        "WorkingDirectory": str(repo),
        "StartInterval": int(FORCE_INTERVAL),
        "RunAtLoad": False,
        "ProcessType": "Background",
        "Nice": 19,
        "StandardOutPath": str(log),
        "StandardErrorPath": str(log),
        "EnvironmentVariables": {"PYTHONUTF8": "1", "LANG": "en_US.UTF-8"},
    }


def _launchctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["launchctl", *args], capture_output=True, text=True, timeout=30)


def install_schedule(python: Path = DEFAULT_PYTHON, start: bool = True) -> dict:
    if not python.exists():
        python = Path(sys.executable)
    path = plist_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    (Path.home() / "Library" / "Logs" / "solmargintrader").mkdir(parents=True, exist_ok=True)
    path.write_bytes(plistlib.dumps(plist_dict(python)))
    path.chmod(0o644)
    out: dict = {"plist": str(path), "label": LABEL, "interval_s": int(FORCE_INTERVAL)}
    if start:
        domain = f"gui/{os.getuid()}"
        _launchctl("bootout", f"{domain}/{LABEL}")   # reload cleanly when already loaded
        boot = _launchctl("bootstrap", domain, str(path))
        out["bootstrap"] = boot.returncode
        if boot.returncode:
            out["bootstrap_error"] = boot.stderr.strip()[:200]
    return out


def uninstall_schedule() -> dict:
    _launchctl("bootout", f"gui/{os.getuid()}/{LABEL}")
    path = plist_path()
    existed = path.exists()
    if existed:
        path.unlink()
    return {"plist": str(path), "removed": existed}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--once", action="store_true")
    ap.add_argument("--force", action="store_true", help="rebuild now in the foreground")
    ap.add_argument("--install-schedule", action="store_true",
                    help="install an hourly launchd agent that runs --once")
    ap.add_argument("--uninstall-schedule", action="store_true")
    ap.add_argument("--run-build", action="store_true", help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if args.install_schedule:
        print(json.dumps(install_schedule(), indent=2))
        return 0
    if args.uninstall_schedule:
        print(json.dumps(uninstall_schedule(), indent=2))
        return 0
    if args.run_build:
        return run_build()
    if args.force:
        return run_build()
    if args.once:
        print(maybe_start())
        return 0
    status, why = semantic_status()
    print(f"semantic index: {status} - {why}")
    print(f"machine idle: {is_idle()} (load {os.getloadavg()[0]:.2f})   rebuild lock free: {lock_free()}")
    return 0 if status == "fresh" else 1


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
